import numpy as np

a = np.array([10, 20, 30, 40, 50, 60])
m = np.arange(12).reshape(3, 4)
print(m)

print("выбрать элементы a по индексам [0, 2, 4];", a[0::2])
print("из матрицы m выбрать элементы (0,1), (1,3), (2,0) - то есть «попарно» индексы строк истолбцов")

rows = np.array([0, 1, 2])
cols = np.array([1, 3, 0])

print(m[rows, cols])

print("из матрицы m выбрать блок из строк [0, 2] и столбцов [1, 3] в виде матрицы 2×2 (а не 4элементов)")
print(m[::2,1:4:2])
